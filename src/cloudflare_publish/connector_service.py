"""The small native user-service contract consumed by connector workflows."""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

from cloudflare_publish.host_platform import HostPlatform
from cloudflare_publish.models import AppPaths, ConnectorStatus
from cloudflare_publish.process import CommandResult, CommandRunner


class ConnectorService(Protocol):
    """One canonical connector user service, with native details behind adapters."""

    @property
    def platform(self) -> HostPlatform: ...

    def which(self, program: str) -> Path | None: ...
    def run(
        self, command: list[str], *, check: bool = True, input_text: str | None = None
    ) -> CommandResult: ...
    def preflight(self) -> None: ...
    def service(self) -> ConnectorStatus | None: ...
    def is_loaded(self) -> bool: ...
    def is_registered(self) -> bool: ...
    def conflicting_services(self) -> tuple[str, ...]: ...
    def validate_definition(self) -> Path: ...
    def install(self, binary: Path) -> None: ...
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def restart(self) -> None: ...
    def wait_until_stopped(self) -> None: ...
    def remove_definition(self) -> None: ...


def build_connector_service(runner: CommandRunner, paths: AppPaths) -> ConnectorService:
    """Select the native adapter from the canonical path set's supported host."""

    if paths.host_platform == "linux":
        from cloudflare_publish.systemd import Systemd

        return Systemd(runner, paths)
    from cloudflare_publish.launchd import Launchd

    return Launchd(runner, paths)
